// backend/services/geminiService.js
// ===================================
// Gemini orchestration layer.
// Gemini receives structured inputs from ML model + cost engine + RAG.
// Gemini NEVER generates attrition probabilities or cost numbers.
// Those come from the ML model and cost engine respectively.

import { GoogleGenerativeAI } from "@google/generative-ai";

let genAI = null;

function getClient() {
  if (!genAI) {
    const key = process.env.GEMINI_API_KEY;
    if (!key || key === "your_gemini_api_key_here") {
      throw new Error("GEMINI_API_KEY not configured. Set it in backend/.env");
    }
    genAI = new GoogleGenerativeAI(key);
  }
  return genAI;
}

/**
 * Generate a structured action plan.
 *
 * Gemini receives:
 *   - ML prediction (prob, risk category, model factors)
 *   - Cost calculations (deterministic — NOT generated by Gemini)
 *   - Replacement scenarios
 *   - Research evidence (from RAG)
 *
 * Gemini returns a structured JSON action plan.
 * Gemini must NOT invent numerical values.
 */
export async function generateActionPlan({
  employeeProfile,
  prediction,
  modelFactors,
  costCalculation,
  replacementScenarios,
  researchEvidence,
  candidateMatches,
}) {
  const client = getClient();
  const modelName = process.env.GEMINI_MODEL || "gemini-2.0-flash";
  const model = client.getGenerativeModel({
    model: modelName,
    generationConfig: { responseMimeType: "application/json" },
  });

  const systemPrompt = `You are an HR analytics research assistant.
You will receive structured data from a machine learning model and deterministic calculations.
You must NOT generate or modify any numerical predictions, probabilities, or cost figures.
Those have already been calculated by the ML model and cost engine.
Your role is to synthesize the information and produce a structured action plan.
Always distinguish between: ML model outputs, deterministic calculations, retrieved evidence, and your recommendations.
Never claim causality. Use "model-associated" not "causes".
Never claim the employee will definitely leave.
Always note that this is decision-support, not an automated employment decision.`;

  const userPrompt = `
EMPLOYEE PROFILE:
${JSON.stringify(employeeProfile, null, 2)}

ML PREDICTION (from trained Logistic Regression model — NOT generated by you):
- Estimated Attrition Probability: ${prediction.probability_pct}%
- Risk Category: ${prediction.risk_category}
- Model: ${prediction.model_name} v${prediction.model_version}
- Calibration: ${prediction.calibration}

MODEL-ASSOCIATED FACTORS (correlations, NOT causes):
${modelFactors.map(f => `- ${f.feature}: ${f.direction} (score: ${f.contribution})`).join('\n')}

REPLACEMENT COST (deterministic calculation — NOT generated by you):
${JSON.stringify(costCalculation?.breakdown || {}, null, 2)}
Total Impact: ${costCalculation?.total_replacement_impact || 'Not calculated'}
Expected Replacement Loss: ${costCalculation?.expected_replacement_loss || 'Not calculated'}

REPLACEMENT SCENARIOS:
${JSON.stringify(replacementScenarios || [], null, 2)}

RESEARCH EVIDENCE (retrieved from knowledge base):
${(researchEvidence || []).map(e => `[${e.source}] ${e.passage}`).join('\n\n')}

CANDIDATE MATCHES:
${JSON.stringify(candidateMatches || [], null, 2)}

Produce a JSON response with this exact structure:
{
  "risk_summary": "2-3 sentence summary of attrition risk. Do not generate probability — reference the ${prediction.probability_pct}% above.",
  "financial_summary": "2-3 sentences on financial exposure using the cost figures above.",
  "replacement_summary": "2-3 sentences on replacement planning.",
  "candidate_summary": "2-3 sentences on candidate matches if provided.",
  "recommended_actions": [
    {"priority": 1, "action": "string", "rationale": "string", "type": "retention|replacement|monitoring"}
  ],
  "evidence_summary": "How research evidence relates to this case.",
  "assumptions": ["List of key assumptions in the cost calculation"],
  "limitations": [
    "Prediction is probabilistic, not deterministic.",
    "Cost figures are user-supplied estimates, not industry standards.",
    "Model-associated factors are correlations, not causes.",
    "This is a research prototype on a synthetic dataset.",
    "This output must NOT be used to make real employment decisions."
  ]
}`;

  const result = await model.generateContent([systemPrompt, userPrompt]);
  const text = result.response.text();

  try {
    return JSON.parse(text);
  } catch {
    return { raw_response: text, parse_error: "Response was not valid JSON" };
  }
}
